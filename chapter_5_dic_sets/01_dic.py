# Python dictionaries are a built-in, versatile data structure used to store data in key-value pairs
# It's unordered
# It's mutable
# It's indexed
# Can't contain duplicate values
capitals = {
    "Pakistan":"Karachi",
    "India":"Delhi",
    "China":"Berlin",
    "Afghanistan":"Kabul",
    "Iran":"Tehran"
}
print(capitals)
print(capitals["Pakistan"])